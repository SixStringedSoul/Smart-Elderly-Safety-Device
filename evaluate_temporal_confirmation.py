"""
Guardian - Temporal Fall Confirmation Evaluation
------------------------------------------------
Evaluates temporal post-processing for the Improved BiGRU model
using the VALIDATION set only.

IMPORTANT:
- The test set is NOT used to choose the temporal rule.
- Validation predictions are grouped by subject + recording and
  sorted by window number so windows from different recordings are
  never mixed.
- This script evaluates consecutive-positive confirmation rules and
  majority-vote rules.

Run from the project root:
    python evaluate_temporal_confirmation.py
"""

from pathlib import Path
import re
import numpy as np
import pandas as pd
import torch
import torch.nn as nn


# =========================
# Configuration
# =========================

PROJECT_ROOT = Path(__file__).resolve().parent

DATA_DIR = PROJECT_ROOT / "processed_data" / "cnn"
MODEL_DIR = PROJECT_ROOT / "models"
RESULTS_DIR = PROJECT_ROOT / "results"

MODEL_PATH = MODEL_DIR / "fall_detection_gru_improved_best.pth"

# Validation files created by prepare_cnn_data.py
X_VAL_PATH = DATA_DIR / "X_validation_raw.npy"
Y_VAL_PATH = DATA_DIR / "y_validation.npy"

# These are generated by train_gru_improved.py
MEAN_PATH = DATA_DIR / "gru_improved_channel_mean.npy"
STD_PATH = DATA_DIR / "gru_improved_channel_std.npy"

# Temporal settings to evaluate
CONSECUTIVE_RULES = [1, 2, 3, 4, 5]
MAJORITY_WINDOWS = [3, 5, 7]

BATCH_SIZE = 512
DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")


# =========================
# Model
# =========================

class ImprovedBiGRU(nn.Module):
    def __init__(self):
        super().__init__()

        self.gru = nn.GRU(
            input_size=6,
            hidden_size=128,
            num_layers=2,
            batch_first=True,
            dropout=0.4,
            bidirectional=True,
        )

        self.classifier = nn.Sequential(
            nn.Linear(256, 64),
            nn.BatchNorm1d(64),
            nn.ReLU(),
            nn.Dropout(0.4),
            nn.Linear(64, 32),
            nn.ReLU(),
            nn.Dropout(0.4),
            nn.Linear(32, 1),
        )

    def forward(self, x):
        out, _ = self.gru(x)
        out = out[:, -1, :]
        return self.classifier(out).squeeze(1)


